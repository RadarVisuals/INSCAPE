import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright-core';
import { browserExecutable } from '../scripts/browserEnvironment.mjs';
import { mountTextToolsFixture } from './fixtures/text-tools-fixture.mjs';
import { openTextToolSection } from './fixtures/text-tool-sections.mjs';

const origin = process.env.INSCAPE_TEXT_ROOT || 'http://127.0.0.1:24970';
const output = process.env.INSCAPE_SYSTEM_WORKFLOW_SCREENSHOT_DIR || '.browser-test-runtime/text-hierarchy';
for (const [width, theme] of [[1440, 'Mist'], [390, 'Carbon']]) test(`Text scopes preserve selection, article defaults, history and search (${width}px)`, { timeout: 60000 }, async () => {
  const browser = await chromium.launch({ executablePath: browserExecutable, headless: true });
  try {
    const page = await browser.newPage({ viewport: { width, height: 1000 }, reducedMotion: 'reduce' });
    page.setDefaultTimeout(10000);
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await mountTextToolsFixture(page, origin);
    const tools = page.locator('.text-tools-window'), body = page.getByRole('textbox', { name: 'Article text', exact: true });
    await page.getByRole('button', { name: 'Settings', exact: true }).click();
    const themeTrigger = page.getByRole('button', { name: /^Menu theme:/ });
    await themeTrigger.scrollIntoViewIfNeeded();
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    await themeTrigger.press('Enter');
    await page.getByRole('option', { name: theme, exact: true }).click();
    await page.getByRole('button', { name: 'Close Settings', exact: true }).click();
    const editor = await body.elementHandle(), saved = () => page.evaluate(() => window.savedDraft());
    const before = await saved(), initialText = await body.innerText();
    const format = tools.getByRole('tab', { name: 'Format text', exact: true });
    const article = tools.getByRole('tab', { name: 'Article settings', exact: true });
    await body.focus(); await body.press('Control+A');
    assert.equal(await tools.getByText('Selected text', { exact: true }).isVisible(), true);
    await article.click();
    assert.equal(await tools.getByLabel('Selected text size', { exact: true }).isVisible(), false);
    assert.equal(await tools.getByLabel('Default font', { exact: true }).isVisible(), false, 'defaults need an explicit action');
    await tools.locator('summary').filter({ hasText: /^Change default style$/ }).click();
    assert.equal(await tools.getByLabel('Default font', { exact: true }).isVisible(), true);
    await article.focus(); await article.press('ArrowLeft');
    assert.equal(await format.getAttribute('aria-selected'), 'true');
    assert.equal(await tools.getByText('Selected text', { exact: true }).isVisible(), true);
    assert.deepEqual(await saved(), before, 'scope navigation is presentation only');
    await tools.getByLabel('Selected text size', { exact: true }).fill('24');
    await tools.getByLabel('Selected text size', { exact: true }).press('Enter');
    const selectedContent = (await saved()).texts[0].article.content;
    assert.equal(await body.locator('span').first().evaluate(node => node.style.fontSize), '24px');
    await mkdir(output, { recursive: true });
    await tools.locator('.text-tools-content').evaluate(node => { node.scrollTop = 0; });
    await tools.screenshot({ path: `${output}/format-${theme.toLowerCase()}-${width}.png` });
    await article.click();
    await tools.locator('summary').filter({ hasText: /^Change default style$/ }).click();
    await tools.screenshot({ path: `${output}/article-collapsed-${theme.toLowerCase()}-${width}.png` });
    await tools.locator('summary').filter({ hasText: /^Change default style$/ }).click();
    await tools.getByLabel('Default text size', { exact: true }).fill('20');
    await tools.getByLabel('Default font', { exact: true }).selectOption('literata');
    assert.deepEqual((await saved()).texts[0].article.content, selectedContent, 'article defaults retain inline overrides');
    assert.equal(await body.locator('span').first().evaluate(node => getComputedStyle(node).fontSize), '24px');
    await tools.getByText('Whole article', { exact: true }).click();
    await tools.screenshot({ path: `${output}/article-${theme.toLowerCase()}-${width}.png` });
    await tools.locator('.text-tools-content').evaluate(node => { node.scrollTop = node.scrollHeight; });
    assert.equal(await format.evaluate(node => { const r = node.getBoundingClientRect(); return node.contains(document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2)); }), true, 'scope tabs stay reachable while scrolling');
    await format.click();
    assert.equal(await tools.locator('.text-tools-content').evaluate(node => node.scrollTop), 0);
    await tools.getByRole('button', { name: 'Undo', exact: true }).click();
    assert.equal(await body.innerText(), initialText, 'Undo keeps the original words');
    assert.equal(await body.locator('span[style*="font-size: 24px"]').count(), 0, 'same editor keeps its inline Undo history');
    assert.equal((await saved()).texts[0].article.appearance.fontSize, 20);
    await article.click(); await body.focus(); await body.press('Control+f');
    assert.equal(await format.getAttribute('aria-selected'), 'true', 'Find reveals the formatting scope');
    assert.equal(await tools.getByRole('textbox', { name: 'Find in article', exact: true }).evaluate(node => document.activeElement === node), true);
    await tools.getByRole('button', { name: 'Close search', exact: true }).click();
    await tools.getByRole('button', { name: 'Focus writing', exact: true }).click();
    const focus = page.getByRole('dialog', { name: 'Focus writing', exact: true }); await focus.waitFor();
    await focus.getByRole('button', { name: 'Return to composition', exact: true }).click();
    assert.equal(await body.evaluate((node, initial) => node === initial, editor), true);
    assert.ok(await tools.locator('.text-tools-content').evaluate(node => node.scrollWidth <= node.clientWidth + 1));
    assert.equal(await tools.locator('input[type="color"]').count(), 0);
    assert.deepEqual(errors, []);
  } finally { await browser.close(); }
});

test('font picker shows rendered fonts, mixed selections and heading defaults without changing the default itself', { timeout: 60000 }, async () => {
  const browser = await chromium.launch({ executablePath: browserExecutable, headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    page.setDefaultTimeout(10000);
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await mountTextToolsFixture(page, origin);
    const tools = page.locator('.text-tools-window'), body = page.getByRole('textbox', { name: 'Article text', exact: true });
    const font = tools.getByLabel('Selected text font', { exact: true });
    const format = () => tools.getByRole('tab', { name: 'Format text', exact: true }).click();
    const defaults = () => openTextToolSection(tools, 'Default text style');
    const choose = async word => {
      await body.focus();
      await body.evaluate((root, word) => {
        const walk = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
        while (walk.nextNode()) {
          const node = walk.currentNode, start = node.textContent.indexOf(word);
          if (start < 0) continue;
          const range = document.createRange(); range.setStart(node, start); range.setEnd(node, start + word.length);
          const selection = getSelection(); selection.removeAllRanges(); selection.addRange(range); return;
        }
        throw Error('Missing selection');
      }, word);
      await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    };
    assert.equal(await font.inputValue(), 'Inscape Sora');
    assert.equal(await tools.getByRole('button', { name: 'Use default font (Sora)', exact: true }).isDisabled(), true);
    await body.fill('First second');
    await defaults(); await tools.getByLabel('Default font', { exact: true }).selectOption('literata');
    await format(); await choose('First');
    assert.equal(await font.inputValue(), 'Inscape Article Literata');
    await font.selectOption('Inscape Article Mono');
    assert.match(await body.locator('span').first().evaluate(node => getComputedStyle(node).fontFamily), /Mono/);
    assert.equal(await page.evaluate(() => window.savedDraft().texts[0].article.font), 'literata');
    await choose('second'); assert.equal(await font.inputValue(), 'Inscape Article Literata');
    await body.press('Control+A');
    assert.equal(await font.locator('option:checked').innerText(), 'Mixed fonts');
    await defaults(); await tools.getByLabel('Default font', { exact: true }).selectOption('sora');
    await format(); await choose('First');
    assert.equal(await font.inputValue(), 'Inscape Article Mono', 'explicit font survives a default change');
    await tools.getByRole('button', { name: 'Use default font (Sora)', exact: true }).click();
    assert.equal(await font.inputValue(), 'Inscape Sora');
    assert.equal(await body.locator('span').count(), 0, 'reset removes the override');
    await tools.getByRole('button', { name: 'Undo', exact: true }).click();
    assert.match(await body.locator('span').first().evaluate(node => getComputedStyle(node).fontFamily), /Mono/);
    await tools.getByRole('button', { name: 'Redo', exact: true }).click();
    await body.focus(); await body.press('Control+A');
    await tools.getByLabel('Paragraph style', { exact: true }).selectOption('1');
    await defaults(); await tools.locator('.text-style-controls summary').click();
    await tools.getByLabel('Style font', { exact: true }).selectOption('Inscape Article Cormorant');
    await format(); await choose('First');
    assert.equal(await font.inputValue(), 'Inscape Article Cormorant', 'heading default matches its rendered font');
    assert.match(await body.locator('h1').evaluate(node => getComputedStyle(node).fontFamily), /Cormorant/);
    await font.selectOption('Inscape Article Mono');
    await tools.getByRole('button', { name: 'Use default font (Cormorant Garamond)', exact: true }).click();
    assert.equal(await font.inputValue(), 'Inscape Article Cormorant');
    assert.equal(await page.evaluate(() => window.savedDraft().texts[0].article.font), 'sora');
    assert.deepEqual(errors, []);
  } finally { await browser.close(); }
});
