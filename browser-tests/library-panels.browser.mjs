import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright-core';
import { browserExecutable } from '../scripts/browserEnvironment.mjs';
import { sharedToolPanel, sharedToolTab } from './fixtures/shared-tools.mjs';
const origin = process.env.INSCAPE_TEST_ORIGIN || 'http://127.0.0.1:5173';
const output = '.browser-test-runtime/library-panels';
const settle = page => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));

for (const [width, theme] of [[1440, 'dark'], [800, 'light']]) test(`Library has one retained host through opening, grouping, docking and reload (${theme})`, { timeout: 90000 }, async () => {
  const browser = await chromium.launch({ executablePath: browserExecutable, headless: true });
  try {
    const page = await browser.newPage({ viewport: { width, height: 900 }, reducedMotion: 'reduce' });
    page.setDefaultTimeout(10000);
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.route('**/*', route => {
      const url = new URL(route.request().url());
      if (url.origin === origin) return route.continue();
      if (url.hostname === 'raw.githubusercontent.com' && url.pathname.includes('/public/'))
        return route.fulfill({ path: 'public/' + url.pathname.split('/public/')[1] });
      return route.abort();
    });
    await page.goto(origin + '/browser-tests/reception-editor-fixture.html?sample&image-choices&session=panel-' + theme);
    const trigger = page.getByRole('button', { name: 'Artwork library', exact: true });
    await trigger.waitFor();
    if (theme === 'light') await page.getByRole('button', { name: 'Switch to Light', exact: true }).click();
    const before = await page.evaluate(() => JSON.stringify(window.receptionFixture.root.getDraft()));
    await trigger.click();
    const library = page.getByRole('region', { name: 'Library workspace', exact: true });
    await library.waitFor(); await settle(page);
    const tab = sharedToolTab(page, 'Library'), panel = sharedToolPanel(page, 'Library');
    assert.equal(await tab.count(), 1);
    await page.evaluate(() => { window.retainedLibrary = document.querySelector('[aria-label="Library workspace"]'); });
    const search = library.getByRole('searchbox', { name: 'Search', exact: true });
    await search.fill('nomad');
    await tab.click({ button: 'right' });
    await page.getByRole('menuitem', { name: 'Detach Library', exact: true }).click();
    await settle(page);
    assert.equal(await sharedToolPanel(page, 'Layers').getByRole('tab', { name: 'Library', exact: true }).count(), 0, 'detaching leaves no duplicate tab');
    assert.equal(await tab.count(), 1);
    assert.equal(await search.inputValue(), 'nomad');
    const floating = await panel.boundingBox();
    await trigger.click(); await settle(page);
    assert.deepEqual(await panel.boundingBox(), floating, 'toolbar focuses without moving or closing');
    assert.equal(await tab.evaluate(node => document.activeElement === node), true);
    await panel.getByRole('button', { name: 'Library window options', exact: true }).click();
    await page.getByRole('menuitemcheckbox', { name: 'Dock on right', exact: true }).click();
    await page.getByRole('button', { name: 'Collapse right sidebar', exact: true }).click();
    assert.equal(await library.isVisible(), false);
    await trigger.click(); await settle(page);
    assert.equal(await library.isVisible(), true);
    assert.equal(await panel.getAttribute('data-dock-side'), 'right');
    await tab.click({ button: 'right' });
    await page.getByRole('menuitem', { name: 'Dock with Inspector', exact: true }).click();
    assert.equal(await sharedToolPanel(page, 'Inspector').getByRole('tab', { name: 'Library', exact: true }).count(), 1);
    await sharedToolTab(page, 'Inspector').click();
    assert.equal(await library.isVisible(), false);
    await trigger.click(); await settle(page);
    assert.equal(await library.isVisible(), true);
    assert.equal(await page.evaluate(() => window.retainedLibrary === document.querySelector('[aria-label="Library workspace"]')), true, 'the original Library content stays mounted');
    await page.getByRole('button', { name: 'Close Library', exact: true }).click();
    assert.equal(await tab.count(), 0);
    await trigger.click(); await settle(page);
    assert.equal(await sharedToolPanel(page, 'Inspector').getByRole('tab', { name: 'Library', exact: true }).count(), 1, 'reopening retains the joined group');
    assert.equal(await search.inputValue(), 'nomad');
    await search.fill('');
    await library.getByRole('button', { name: 'Library display options', exact: true }).click();
    await page.getByRole('button', { name: 'Icons', exact: true }).click();
    await page.getByRole('slider', { name: 'Card size', exact: true }).fill('80');
    await page.keyboard.press('Escape');
    await tab.click({ button: 'right' });
    await page.getByRole('menuitem', { name: 'Dock below Inspector', exact: true }).click();
    await page.getByRole('separator', { name: 'Resize Inspector and Library panels', exact: true }).waitFor();
    assert.equal(await library.isVisible(), true);
    await mkdir(output, { recursive: true });
    await page.screenshot({ path: output + '/' + theme + '-stacked.png' });
    await page.reload(); await library.waitFor();
    await page.getByRole('separator', { name: 'Resize Inspector and Library panels', exact: true }).waitFor();
    assert.equal(await tab.count(), 1);
    assert.equal(await page.locator('.system-workflow__library').count(), 1);
    const sizes = await library.locator('.lattice-browser-asset__media').evaluateAll(nodes => nodes.map(node => { const r = node.getBoundingClientRect(); return [r.width, r.height]; }));
    assert.ok(sizes.length > 0); assert.ok(sizes.every(([w, h]) => Math.abs(w - h) < 1));
    assert.equal(await page.evaluate(() => JSON.stringify(window.receptionFixture.root.getDraft())), before, 'panel changes never author content');
    assert.deepEqual(errors, []);
  } finally { await browser.close(); }
});
