import { chromium } from 'playwright-core';
import { resetCameraTestView } from './fixtures/workbench-camera-test.mjs';
import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { join } from 'node:path';
import { browserExecutable } from '../scripts/browserEnvironment.mjs';
import { openTextToolSection } from './fixtures/text-tool-sections.mjs';
import { hideWorkspaceSidebar } from './fixtures/workspace-sidebar.mjs';
import { openSharedTool, sharedToolPanel } from './fixtures/shared-tools.mjs';
const origin = process.env.INSCAPE_TEXT_ROOT || 'http://127.0.0.1:5297';

test('reload restores local arrangement and native Text can recover from a failed save', { timeout: 120000 }, async () => {
  const shots = process.env.INSCAPE_BROWSER_OUTPUT || '.browser-test-runtime/workbench-recovery';
  await mkdir(shots, { recursive: true });
  console.log(`Screenshots: ${shots}`);
  const browser = await chromium.launch({ executablePath: browserExecutable, headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
    page.setDefaultTimeout(10000);
    const errors = []; page.on('pageerror', e => { errors.push(e.message); console.error(e.message); });
    await page.route('**/*', r => new URL(r.request().url()).origin === origin ? r.continue() : r.abort());
    await page.goto(`${origin}/browser-tests/workbench-recovery-fixture.html`);
    const text = page.locator('aside.text-window');
    await page.getByRole('button', { name: 'Close Inspector', exact: true }).click();
    await openSharedTool(page, 'Layers');
    await page.getByRole('button', { name: 'Close Workbench Layers', exact: true }).click();
    await hideWorkspaceSidebar(page);
    await resetCameraTestView(page);
    const drag = async (handle, dx, dy) => {
      const b = await handle.boundingBox(); await page.mouse.move(b.x + 10, b.y + b.height / 2); await page.keyboard.down('Alt');
      await page.mouse.down(); await page.mouse.move(b.x + 10 + dx, b.y + b.height / 2 + dy, { steps: 5 }); await page.mouse.up(); await page.keyboard.up('Alt');
    };
    await drag(page.getByLabel('Move Text window', { exact: true }), 23, 41);
    await drag(page.getByRole('separator', { name: 'Resize Text window', exact: true }), 19, 37);
    const before = { text: await text.boundingBox(), draft: await page.evaluate(() => window.readDraft()) };
    await page.waitForFunction(() => window.readPreferences()?.docks.hidden.includes('Layers'));
    await page.screenshot({ path: join(shots, 'before-reload.png') });
    await page.reload(); await text.waitFor();
    await resetCameraTestView(page);
    const near = (actual, expected) => { for (const key of ['x', 'y', 'width', 'height']) assert.ok(Math.abs(actual[key] - expected[key]) < 1, `${key}: ${actual[key]} != ${expected[key]}`); };
    near(await text.boundingBox(), before.text);
    assert.equal(await page.getByRole('button', { name: 'Close Inspector', exact: true }).count(), 0);
    assert.equal(await page.getByRole('tab', { name: 'Layers', exact: true }).count(), 0);
    assert.equal(await page.evaluate(() => window.readPreferences().docks.hidden.includes('Layers')), true);
    assert.deepEqual(await page.evaluate(() => window.readDraft()), before.draft, 'restoring layout does not edit the canonical draft');
    await page.screenshot({ path: join(shots, 'after-reload.png') });
    const editor = page.getByRole('textbox', { name: 'Article text', exact: true });
    await editor.fill('Saved sentence.');
    await page.getByRole('button', { name: 'Open text inspector', exact: true }).click();
    const title = text.getByRole('textbox', { name: 'Article title', exact: true });
    await title.fill('// ARRIVAL');
    const inspector = sharedToolPanel(page);
    await openTextToolSection(inspector, 'Title');
    const titleSize = inspector.getByLabel('Title size', { exact: true });
    assert.equal(await titleSize.inputValue(), '', 'automatic title size has no explicit override');
    assert.equal(await titleSize.getAttribute('placeholder'), '28');
    assert.equal(await title.evaluate(node => getComputedStyle(node).fontSize), '28px');
    await inspector.getByLabel('Title size', { exact: true }).fill('64');
    assert.equal(await title.evaluate(node => getComputedStyle(node).fontSize), '64px');
    await openTextToolSection(inspector, 'Default text style');
    await inspector.getByLabel('Default font', { exact: true }).selectOption('literata');
    assert.match(await editor.evaluate(node => getComputedStyle(node).fontFamily), /Literata/);
    assert.match(await title.evaluate(node => getComputedStyle(node).fontFamily), /Literata/);
    assert.equal(await inspector.getByLabel('Default font', { exact: true }).inputValue(), 'literata');
    await page.evaluate(() => { window.failDraft = true; });
    await editor.fill('Keep this unsaved sentence.');
    await page.getByRole('button', { name: 'Retry local save', exact: true }).waitFor();
    assert.equal(await page.getByRole('button', { name: 'Preview', exact: true }).isDisabled(), true);
    await resetCameraTestView(page);
    assert.equal(await editor.innerText(), 'Keep this unsaved sentence.');
    await page.evaluate(() => { window.failDraft = false; });
    await page.getByRole('button', { name: 'Retry local save', exact: true }).click();
    assert.equal(await page.locator('.system-workflow__recovery-notice').count(), 0);
    assert.ok(JSON.stringify(await page.evaluate(() => window.readDraft())).includes('Keep this unsaved sentence.'));
    const raw = await page.evaluate(() => window.readRawDraft());
    for (const draft of raw.workbenches?.map(item => item.content) || [raw]) {
      assert.equal(Object.hasOwn(draft, 'grids'), false);
      assert.equal(Object.hasOwn(draft, 'displays'), false);
      assert.equal(Object.hasOwn(draft.workbench, 'display'), false);
    }
    assert.equal(await title.evaluate(node => getComputedStyle(node).fontSize), '64px');
    await page.reload();
    assert.equal(await title.evaluate(node => getComputedStyle(node).fontSize), '64px');
    await page.evaluate(() => { window.failLayout = true; });
    await drag(page.getByLabel('Move Text window', { exact: true }), 11, 7);
    await page.getByRole('button', { name: 'Save current layout', exact: true }).waitFor();
    await page.evaluate(() => { window.failLayout = false; });
    await page.getByRole('button', { name: 'Save current layout', exact: true }).click();
    assert.equal(await page.locator('.system-workflow__layout-notice').count(), 0);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: join(shots, 'narrow-restored.png') });
    assert.deepEqual(errors, []);
  } finally { await browser.close(); }
});
