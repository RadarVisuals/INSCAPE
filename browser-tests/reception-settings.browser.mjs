import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright-core';
import { browserExecutable } from '../scripts/browserEnvironment.mjs';
const origin = process.env.INSCAPE_TEST_ROOT || 'http://127.0.0.1:5197';
const output = process.env.INSCAPE_SCREENSHOT_DIR || '.browser-test-runtime/reception-settings';
const button = (page, name) => page.getByRole('button', { name, exact: true });
async function openSettings(page, tab) {
  if (!await button(page, 'Close Settings').isVisible()) await button(page, 'Settings').click();
  await page.getByRole('tab', { name: tab, exact: true }).click();
}
for (const width of [1920, 390]) test(`Reception simplified start, grid, header and appearance at ${width}`, { timeout: 60000 }, async () => {
  const browser = await chromium.launch({ executablePath: browserExecutable, headless: true });
  const page = await browser.newPage({ viewport: { width, height: width === 1920 ? 1080 : 844 }, hasTouch: width === 390 });
  page.setDefaultTimeout(12000);
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.route('**/*', route => new URL(route.request().url()).origin === origin ? route.continue() : route.abort());
  try {
    await page.goto(`${origin}/browser-tests/reception-editor-fixture.html?session=${crypto.randomUUID()}`);
    await button(page, 'Image from Library').waitFor();
    assert.equal(await page.locator('[data-selected], .reception-selection').count(), 0);
    for (const name of ['Saved content', 'Page settings', 'Profile', 'Cell options', 'Move or swap content', 'Join with neighbor', 'Link canvas content', 'Grid settings', 'Cell appearance', 'Appearance'])
      assert.equal(await button(page, name).count(), 0, name + ' is absent');
    assert.equal(await button(page, 'New Text').count(), 1);
    assert.equal(await button(page, 'Add cell').count(), 1);
    await mkdir(output, { recursive: true });
    await page.screenshot({ path: `${output}/blank-${width}.png` });
    await openSettings(page, 'Grid');
    assert.equal(await page.getByLabel('Header name', { exact: true }).count(), 0);
    assert.equal(await button(page, 'Settings').count(), 1);
    assert.equal(await page.getByRole('tab', { name: 'Text', exact: true }).isVisible(), true);
    await page.getByRole('tab', { name: 'Text', exact: true }).click();
    assert.equal(await page.getByRole('slider', { name: 'Content spacing', exact: true }).isDisabled(), true);
    assert.equal(await page.getByRole('checkbox', { name: 'Apply to all', exact: true }).isChecked(), false);
    await page.getByRole('tab', { name: 'Grid', exact: true }).click();
    assert.equal(await page.getByRole('region', { name: 'Settings', exact: true }).locator('.ds-colour-controls').count(), 0);
    const corners = page.getByRole('slider', { name: 'Corners', exact: true });
    await corners.press('ArrowRight');
    await page.waitForFunction(() => receptionFixture.root.getSnapshot().reception.radius === 21);
    const currentView = page.getByRole('group', { name: 'Your current view', exact: true });
    const visitorDefault = page.getByRole('group', { name: 'Default for visitors', exact: true });
    await visitorDefault.scrollIntoViewIfNeeded();
    const currentBox = await currentView.boundingBox(), visitorBox = await visitorDefault.boundingBox();
    assert.ok(visitorBox.x >= currentBox.x + currentBox.width, 'View and visitor appearance controls sit side by side');
    assert.ok(Math.abs(visitorBox.y - currentBox.y) <= 1, 'Both appearance groups share the same row');
    await page.screenshot({ path: `${output}/settings-grid-theme-${width}.png` });
    await button(page, 'Grid color').click();
    await page.getByRole('textbox', { name: 'Color colour', exact: true }).fill('#345678');
    await page.getByRole('textbox', { name: 'Color colour', exact: true }).press('Enter');
    await page.waitForFunction(() => receptionFixture.root.getSnapshot().reception.surface === '#345678');
    assert.equal(await page.locator('.reception-region').evaluate(n => getComputedStyle(n).backgroundColor), 'rgb(52, 86, 120)');
    assert.equal(await button(page, 'Close Color').isVisible(), true);
    assert.equal(await button(page, 'Close Settings').isVisible(), true);
    await page.screenshot({ path: `${output}/grid-settings-${width}.png` });
    await button(page, 'Close Color').click();
    await button(page, 'Close Settings').click();
    await page.locator('[data-region-id]').press('Enter');
    await button(page, 'Cell color').click();
    assert.equal((await page.getByRole('textbox', { name: 'Color colour', exact: true }).inputValue()).toLowerCase(), '#345678', 'cell controls inherit the grid background');
    await button(page, 'Close Color').click();
    await button(page, 'Edit name and logo').click();
    await page.getByRole('textbox', { name: 'Header name', exact: true }).fill('My studio');
    await page.getByRole('textbox', { name: 'Header name', exact: true }).press('Enter');
    await page.waitForFunction(() => receptionFixture.root.getSnapshot().reception.branding.name === 'My studio');
    assert.equal(await page.locator('.reception-brand').innerText(), 'My studio');
    assert.equal(await page.locator('.reception-logo-option svg').count(), 1, 'portrait choice is visual');
    await button(page, 'Close Header').click();
    await button(page, 'Edit name and logo').click();
    await page.getByRole('textbox', { name: 'Header name', exact: true }).fill('Studio saved on blur');
    await openSettings(page, 'Grid');
    await page.waitForFunction(() => receptionFixture.root.getSnapshot().reception.branding.name === 'Studio saved on blur');
    await button(page, 'Close Settings').click();
    await button(page, 'Use light appearance').click();
    assert.equal(await button(page, 'Close Settings').count(), 0, 'The navigation theme toggle remains immediate');
    assert.equal(await button(page, 'Close Appearance').count(), 0);
    assert.equal(await page.locator('[data-reception-editor]').getAttribute('data-menu-surface'), 'mist');
    assert.equal(await page.evaluate(() => receptionFixture.root.getSnapshot().reception.branding.theme), 'carbon');
    await button(page, 'Use dark appearance').click();
    await openSettings(page, 'Grid');
    await page.getByRole('group', { name: 'Your current view', exact: true }).getByRole('button', { name: 'Light', exact: true }).click();
    assert.equal(await page.locator('[data-reception-editor]').getAttribute('data-menu-surface'), 'mist');
    assert.equal(await page.evaluate(() => receptionFixture.root.getSnapshot().reception.branding.theme), 'carbon');
    await page.getByRole('group', { name: 'Default for visitors', exact: true }).getByRole('button', { name: 'Light', exact: true }).click();
    assert.equal(await page.evaluate(() => receptionFixture.publish().reception.branding.theme), 'mist');
    await button(page, 'Close Settings').click();
    await page.reload(); await button(page, 'Settings').waitFor();
    assert.equal(await page.locator('.reception-brand').innerText(), 'Studio saved on blur');
    assert.equal(await page.locator('.reception-region').evaluate(n => getComputedStyle(n).backgroundColor), 'rgb(52, 86, 120)');
    assert.equal(await page.locator('.reception-editor-window').evaluate(n => n.scrollWidth <= n.clientWidth + 1), true);
    assert.deepEqual(errors, []);
  } finally { await browser.close(); }
});


test('Settings holds layout while dedicated Text tools and persistent Color follow writing', { timeout: 90000 }, async () => {
  const browser = await chromium.launch({ executablePath: browserExecutable, headless: true });
  const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
  page.setDefaultTimeout(12000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.route('**/*', route => new URL(route.request().url()).origin === origin ? route.continue() : route.abort());
  const settings = page.getByRole('region', { name: 'Settings', exact: true });
  const textTools = page.getByRole('region', { name: 'Text', exact: true });
  const color = page.getByRole('region', { name: 'Color', exact: true });
  const textTab = page.getByRole('tab', { name: 'Text', exact: true });
  const state = () => page.evaluate(() => receptionFixture.root.getSnapshot().reception);
  const zIndex = panel => panel.evaluate(node => Number(getComputedStyle(node).zIndex));
  const paint = async value => {
    const field = color.getByRole('textbox', { name: 'Color colour', exact: true });
    await field.fill(value); await field.press('Enter');
    assert.equal(await color.isVisible(), true, 'Color stays open after applying a colour');
  };
  try {
    await page.goto(`${origin}/browser-tests/reception-editor-fixture.html?session=${crypto.randomUUID()}`);
    await button(page, 'New Text').click();
    await page.getByRole('textbox', { name: 'Article text', exact: true }).waitFor();
    assert.equal(await textTools.isVisible(), true, 'New Text opens its dedicated Text tools');
    assert.equal(await settings.count(), 0, 'Writing does not open Settings');
    assert.equal(await textTools.getByRole('button', { name: 'Bold', exact: true }).isVisible(), true);
    assert.equal(await textTools.locator('.ds-studio-colour-wheel').count(), 0, 'Text colours live in Color');
    assert.equal(await button(page, 'Cell appearance').count(), 0);
    assert.equal(await button(page, 'Settings').count(), 1);
    await openSettings(page, 'Text');
    assert.equal(await textTab.getAttribute('aria-selected'), 'true');
    assert.equal(await page.getByRole('tab', { name: 'Grid', exact: true }).isVisible(), true);
    assert.equal(await settings.getByRole('button', { name: 'Bold', exact: true }).count(), 0, 'Settings contains layout rather than the Text tools');
    assert.equal(await settings.getByRole('tab', { name: 'Format text', exact: true }).count(), 0);
    assert.equal(await settings.locator('.ds-studio-colour-wheel').count(), 0);
    assert.equal(await page.getByRole('slider', { name: 'Content spacing', exact: true }).inputValue(), '24');
    assert.equal(await page.getByRole('checkbox', { name: 'Apply to all', exact: true }).isChecked(), false);
    await button(page, 'Close Settings').click();
    await button(page, 'Edit text').click();
    await textTools.waitFor();
    assert.equal(await settings.count(), 0, 'Edit text opens Text instead of Settings');
    await page.getByRole('textbox', { name: 'Article title', exact: true }).fill('First composition');
    await page.getByRole('textbox', { name: 'Article text', exact: true }).fill('Saved while switching between my tools.');
    const first = (await state()).regions[0].id;
    await button(page, 'Cell color').click();
    await color.waitFor();
    assert.equal(await textTools.isVisible(), true, 'The palette is independent from Text tools');
    assert.equal(await color.getByRole('slider', { name: 'Content spacing', exact: true }).count(), 0);
    assert.equal(await color.getByLabel('Include in publication', { exact: true }).count(), 0);
    await paint('#345678');
    assert.equal((await state()).regions.find(cell => cell.id === first).surface, '#345678');
    await color.getByRole('group', { name: 'Apply color to', exact: true }).getByRole('button', { name: 'Text', exact: true }).click();
    const colorTarget = color.getByRole('combobox', { name: 'Color target', exact: true });
    assert.equal(await colorTarget.inputValue(), 'default');
    await colorTarget.focus();
    assert.ok(await zIndex(color) > await zIndex(textTools), 'Portalled Text color controls activate the Color window');
    await textTools.getByRole('button', { name: 'Bold', exact: true }).focus();
    assert.ok(await zIndex(textTools) > await zIndex(color), 'Portalled formatting controls activate the Text window');
    await paint('#eeddcc');
    assert.ok(await zIndex(color) > await zIndex(textTools));
    const firstText = (await state()).regions.find(cell => cell.id === first).content;
    assert.equal((await state()).texts.find(item => item.id === firstText).article.appearance.color, '#eeddcc');
    assert.equal((await state()).regions.find(cell => cell.id === first).surface, '#345678', 'Text colour leaves the cell background intact');
    assert.equal(await textTools.locator('.ds-studio-colour-wheel').count(), 0);
    await mkdir(output, { recursive: true });
    await page.screenshot({ path: `${output}/text-tools-and-text-color-1920.png` });
    await color.getByRole('group', { name: 'Apply color to', exact: true }).getByRole('button', { name: 'Background', exact: true }).click();
    await button(page, 'Add cell').click(); await button(page, 'Beside').click();
    assert.equal(await color.isVisible(), true, 'Color survives adding another cell');
    await page.locator('[data-selected]').getByRole('button', { name: 'New Text', exact: true }).click();
    await page.getByRole('textbox', { name: 'Article text', exact: true }).waitFor();
    assert.equal(await textTools.isVisible(), true);
    assert.equal(await settings.count(), 0);
    const second = (await state()).regions.find(cell => cell.id !== first).id;
    await page.getByRole('textbox', { name: 'Article title', exact: true }).fill('Second composition');
    await page.getByRole('textbox', { name: 'Article text', exact: true }).fill('Another writing cell.');
    await paint('#654321');
    assert.equal((await state()).regions.find(cell => cell.id === second).surface, '#654321');
    assert.equal((await state()).regions.find(cell => cell.id === first).surface, '#345678');
    await openSettings(page, 'Text');
    assert.equal(await color.isVisible(), true, 'Color remains independent while Settings is open');
    await page.locator(`[data-region-id="${first}"]`).press('Enter');
    assert.equal(await settings.isVisible(), true, 'Selecting another cell keeps Settings open');
    assert.equal(await color.isVisible(), true, 'Selecting another cell keeps Color open');
    assert.equal(await page.getByRole('textbox', { name: 'Article title', exact: true }).inputValue(), 'First composition');
    assert.equal((await color.getByRole('textbox', { name: 'Color colour', exact: true }).inputValue()).toLowerCase(), '#345678');
    await paint('#446688');
    assert.equal((await state()).regions.find(cell => cell.id === first).surface, '#446688');
    assert.equal((await state()).regions.find(cell => cell.id === second).surface, '#654321');
    await page.screenshot({ path: `${output}/settings-and-persistent-color-1920.png` });
    await button(page, 'Close Color').focus();
    await button(page, 'Close Color').press('Enter');
    await page.waitForFunction(id => document.activeElement?.dataset.regionId === id, first);
    await page.getByRole('main', { name: 'Reception editor', exact: true }).click({ position: { x: 3, y: 3 } });
    assert.equal(await page.locator('[data-selected]').count(), 0);
    assert.equal(await settings.isVisible(), true, 'Deselecting keeps Settings available');
    assert.equal(await textTab.isVisible(), true);
    assert.equal(await page.getByRole('slider', { name: 'Content spacing', exact: true }).isDisabled(), true);
    await button(page, 'Close Settings').click();
    await page.locator(`[data-region-id="${second}"]`).press('Enter');
    await button(page, 'Edit text').click();
    assert.equal(await textTools.isVisible(), true, 'Edit text opens its dedicated tools');
    assert.equal(await settings.count(), 0);
    assert.equal(await textTools.getByRole('button', { name: 'Bold', exact: true }).isVisible(), true);
    await button(page, 'Preview').click();
    assert.equal(await settings.count(), 0); assert.equal(await textTools.count(), 0); assert.equal(await color.count(), 0);
    await page.getByText('Saved while switching between my tools.', { exact: true }).waitFor();
    await page.getByText('Another writing cell.', { exact: true }).waitFor();
    const saved = await state();
    await page.reload(); await button(page, 'Settings').waitFor();
    assert.deepEqual(await state(), saved);
    assert.deepEqual(errors, []);
  } finally { await browser.close(); }
});
