import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright-core';
import { browserExecutable } from '../scripts/browserEnvironment.mjs';

const output = process.env.INSCAPE_BROWSER_OUTPUT || '.browser-test-runtime/keeper-screen';
const origin = process.env.INSCAPE_TEXT_ROOT || 'http://127.0.0.1:24970';
const settle = page => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
const near = (a, b) => assert.ok(Math.abs(a - b) < 1.1, `${a} != ${b}`);
const hit = node => { const r = node.getBoundingClientRect(); return node.contains(document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2)); };

for (const width of [1440, 390]) test(`Keeper belongs to the screen and follows Workbench switches (${width}px)`, { timeout: 45000 }, async () => {
  const browser = await chromium.launch({ executablePath: browserExecutable, headless: true });
  try {
    const page = await browser.newPage({ viewport: { width, height: 900 }, reducedMotion: 'reduce' });
    page.setDefaultTimeout(8000);
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.route('**/*', route => new URL(route.request().url()).origin === origin ? route.continue() : route.abort());
    await page.goto(`${origin}/browser-tests/tool-chrome-fixture.html?sample=keeper&theme=${width === 390 ? 'carbon' : 'mist'}`);
    const dock = page.locator('.keeper-dock-window'), trigger = page.getByRole('button', { name: 'Keeper settings', exact: true });
    await trigger.waitFor(); await settle(page);
    const initial = await dock.boundingBox();
    near(initial.x + initial.width, width - 16);
    const rail = await page.getByRole('group', { name: 'Workbench zoom', exact: true }).boundingBox();
    assert.ok(initial.y + initial.height <= rail.y - 7 && initial.y + initial.height >= rail.y - 20);
    assert.equal(await trigger.evaluate(hit), true);
    assert.equal(await dock.evaluate(node => Boolean(node.closest('.workbench-canvas-content'))), false);
    const before = await page.evaluate(() => window.readToolChromeDraft());
    const board = page.locator('.system-workflow__presentation-board').first();
    const boardBefore = await board.boundingBox();
    const host = page.locator('main.system-workflow');
    await host.dispatchEvent('wheel', { deltaY: -180, ctrlKey: true, clientX: 180, clientY: 220, bubbles: true, cancelable: true });
    await settle(page);
    assert.notEqual((await board.boundingBox()).width, boardBefore.width, 'the actual canvas zooms');
    assert.deepEqual(await dock.boundingBox(), initial, 'zoom cannot move or scale Keeper');
    await host.dispatchEvent('wheel', { deltaY: 80, deltaX: 60, bubbles: true, cancelable: true });
    await settle(page);
    assert.deepEqual(await dock.boundingBox(), initial, 'panning cannot move Keeper');
    const move = dock.getByLabel('Move Keeper dock window', { exact: true });
    await move.focus(); await move.press('Shift+ArrowLeft'); await move.press('ArrowUp');
    const moved = await dock.boundingBox(); assert.ok(moved.x < initial.x && moved.y < initial.y);
    assert.deepEqual(await page.evaluate(() => window.readToolChromeDraft()), before, 'moving the dock does not author canvas content');
    const selector = page.getByRole('combobox', { name: 'Active Workbench' });
    const first = await selector.inputValue();
    await page.getByRole('button', { name: 'New', exact: true }).click();
    await page.getByLabel('New Workbench name').fill('Second composition');
    await page.getByRole('button', { name: 'Create Workbench', exact: true }).click();
    await trigger.waitFor(); await settle(page);
    const second = await selector.inputValue(); assert.notEqual(second, first);
    assert.deepEqual((await page.evaluate(() => window.readToolChromeDraft())).keeperDocks, before.keeperDocks);
    near((await dock.boundingBox()).x, moved.x); near((await dock.boundingBox()).y, moved.y);
    await trigger.click();
    await page.getByLabel('Keeper name', { exact: true }).fill('Same companion');
    await page.getByLabel('Keeper name', { exact: true }).press('Enter');
    await page.getByRole('button', { name: 'Close Keeper settings', exact: true }).click();
    await selector.selectOption(first); await trigger.waitFor(); await settle(page);
    const shared = await page.evaluate(() => window.readToolChromeDraft());
    assert.equal(shared.keeperDocks[0].id, before.keeperDocks[0].id);
    assert.equal(shared.keeperDocks[0].name, 'Same companion');
    const { workbench: beforeLayout, keeperDocks: beforeKeepers, ...beforeContent } = before;
    const { workbench: afterLayout, keeperDocks: afterKeepers, ...afterContent } = shared;
    assert.deepEqual(afterContent, beforeContent, 'Keeper edits do not edit this composition');
    assert.equal(afterLayout?.keeperDocks, undefined, 'switching saves canvas geometry without Keeper screen positions');
    near((await dock.boundingBox()).x, moved.x); near((await dock.boundingBox()).y, moved.y);
    await mkdir(output, { recursive: true });
    await page.screenshot({ path: `${output}/screen-${width}.png` });
    assert.deepEqual(errors, []);
  } finally { await browser.close(); }
});
