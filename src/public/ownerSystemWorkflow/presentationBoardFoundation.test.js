import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import test from 'node:test';

const read = (path) => readFileSync(new URL(path, import.meta.url), 'utf8');

test('owner Presentation Board reuses the existing interactive canvas inside one clipped Stage', () => {
  const runtime = read('./OwnerSystemWorkflowRuntime.jsx');
  const board = read('./PresentationBoardDefinitive.jsx');
  const canvas = read('./OwnerSystemWorkflowCanvas.jsx');
  const geometry = read('./presentationBoardGeometry.js');
  const styles = read('./ownerSystemWorkflow.css');

  assert.match(runtime, /<PresentationBoard[\s\S]*<OwnerSystemWorkflowCanvas[\s\S]*<\/PresentationBoard>/);
  assert.match(board, /data-presentation-workbench/);
  assert.match(board, /data-presentation-stage/);
  assert.match(board, /transform: `scale\(\$\{displayScale\}\)`/);
  assert.doesNotMatch(board, /aria-label="Board zoom"|type="range"|Board zoom percentage/);
  assert.match(board, /aria-label=\{maximized \? 'Restore Presentation Board' : 'Maximize Presentation Board'\}/);
  assert.match(board, /aria-label="Close Presentation Board to shortcut"/);
  assert.match(board, /shortcutName[\s\S]*onDoubleClick/);
  assert.match(board, /cloneElement\(children, \{[\s\S]*boardScale: displayScale,[\s\S]*interactionDisabled:/);
  assert.match(board, /onContextMenu=\{onContextMenu\}/);
  assert.match(board, /beginBoardDrag[\s\S]*setBoardPosition/);
  assert.match(runtime, /OwnerSystemWorkflowMetadataModule/);
  assert.match(runtime, /label: 'ADD'[\s\S]*label: 'PRESENTATION BOARD'[\s\S]*label: 'METADATA MODULE'/);
  assert.match(runtime, /useOwnerSystemWorkflowFocusViewer/);
  assert.match(runtime, /<OwnerSystemWorkflowFocusViewer/);
  assert.match(runtime, /renderInspection=\{viewer\.placementId \? \(container, controlsContainer\) => <OwnerSystemWorkflowFocusViewer[\s\S]*container=\{container\} controlsContainer=\{controlsContainer\}/);
  assert.match(board, /'window'[\s\S]*'maximizing'[\s\S]*'maximized'[\s\S]*'restoring'/);
  assert.match(board, /resizePresentationBoardFromCorner/);
  assert.match(board, /corners\.map/);
  assert.match(board, /sidecarWidth: sidecarOpen \? metadataWidth : 0/);
  assert.match(board, /presentationBoardInspectionFrame\(view,[\s\S]*host\?\.clientWidth[\s\S]*geometryOptions/);
  assert.match(board, /PRESENTATION_BOARD_METADATA_SIDECAR\.trackWidth/);
  assert.match(geometry, /trackWidth: 286/);
  assert.match(geometry, /gap: 8/);
  assert.doesNotMatch(board, /OWNER/);
  assert.match(board, /LatticePixelGrid/);
  assert.match(board, /application\/x-inscape-asset/);
  assert.match(board, /RENAME/);
  assert.match(board, /metadataProjection === 'down'/);
  assert.match(board, /metadataProjection === 'side'/);
  assert.match(board, /aria-label="Undock Metadata"/);
  assert.match(board, /system-workflow__board-inspection-controls-host/);
  assert.match(board, /renderInspection\(inspectionHost, inspectionControlsHost\)/);
  assert.match(canvas, /system-workflow__stage-content/);
  assert.match(canvas, /onDoubleClick[\s\S]*onOpenViewer/);
  assert.doesNotMatch(`${board}\n${canvas}\n${styles}`, /system-workflow__camera-plane|workflow-camera|view\.camera/);
  assert.match(styles, /\.system-workflow__stage \{[^}]*aspect-ratio: 16 \/ 9;[^}]*overflow: clip;[^}]*transform-origin: top left;/s);
  assert.match(styles, /\.system-workflow__presentation-board \{[^}]*--workflow-board-frame-gap: 8px;/s);
  assert.match(styles, /\.system-workflow__presentation-board::before \{[^}]*border: 1px solid var\(--workflow-border-strong\);[^}]*border-radius: var\(--workflow-board-radius\)/s);
  assert.match(styles, /\.system-workflow__presentation-board\[data-metadata-sidecar\]::before \{[^}]*var\(--workflow-metadata-width\)[^}]*var\(--workflow-board-frame-gap\)/s);
  assert.match(styles, /\.system-workflow__board-resize-handle \{[^}]*position: absolute;/s);
  assert.doesNotMatch(styles, /system-workflow__board-resize-handle::after/);
  assert.match(styles, /\.system-workflow__desktop-shortcut \{[^}]*position: absolute;/s);
  assert.match(styles, /system-workflow__metadata-projection\.is-side/);
  assert.match(styles, /\.system-workflow__metadata-projection\.is-side \{[^}]*bottom: calc\(-1 \* var\(--workflow-board-frame-gap\)\);[^}]*left: calc\(100% \+ var\(--workflow-board-frame-gap\)\);[^}]*width: calc\(var\(--workflow-metadata-width, 286px\) - var\(--workflow-board-frame-gap\)\);[^}]*padding-block: var\(--workflow-board-frame-gap\);[^}]*overflow: hidden;/s);
  assert.match(styles, /\.system-workflow__metadata-side-scroll \{[^}]*overflow-y: auto;[^}]*clip-path: inset\(0 round var\(--workflow-board-radius\)\);[^}]*scrollbar-width: none;/s);
  assert.match(styles, /\.system-workflow__metadata-side-scroll::\-webkit-scrollbar \{[^}]*display: none;/s);
  assert.match(styles, /\.system-workflow__metadata-down-host \{[^}]*--workflow-metadata-outward-radius: calc\(var\(--workflow-board-radius\) \* 1\.5\);[^}]*right: 0;[^}]*width: var\(--workflow-metadata-width, 286px\);[^}]*overflow: visible;/s);
  assert.match(styles, /\.system-workflow__metadata-projection\.is-down \{[^}]*width: 100%;[^}]*max-height: 60%;[^}]*padding: var\(--workflow-board-frame-gap\) 0 var\(--workflow-board-frame-gap\) var\(--workflow-board-frame-gap\);[^}]*overflow: hidden;/s);
  assert.match(styles, /\.system-workflow__metadata-down-host::before,[\s\S]*?-webkit-mask: radial-gradient\(circle var\(--workflow-metadata-outward-radius\) at bottom left,/s);
  assert.match(styles, /\.system-workflow__metadata-down-host::before \{[^}]*left: calc\(-1 \* var\(--workflow-metadata-outward-radius\)\);/s);
  assert.match(styles, /\.system-workflow__metadata-down-host::after \{[^}]*align-self: flex-end;/s);
  assert.match(styles, /\.system-workflow__metadata-down-scroll \{[^}]*min-height: 0;[^}]*overflow-y: auto;[^}]*border-radius: var\(--workflow-board-radius\);[^}]*clip-path: inset\(0 round var\(--workflow-board-radius\)\);[^}]*scrollbar-width: none;/s);
  assert.match(styles, /\.system-workflow__metadata-down-scroll::\-webkit-scrollbar \{[^}]*display: none;/s);
  assert.match(styles, /\.system-workflow__metadata-projection\.is-down \.system-workflow__metadata-module-content \{[^}]*padding: 0;/s);
  assert.match(styles, /\.system-workflow__metadata-module-content \{[^}]*padding: var\(--workflow-board-frame-gap, 8px\);[^}]*gap: var\(--workflow-board-frame-gap, 8px\)/s);
  assert.match(styles, /\.system-workflow__metadata-projection\.is-side \.system-workflow__metadata-module-content \{[^}]*padding-right: 0;[^}]*padding-bottom: 0;/s);
  assert.match(styles, /\.system-workflow__stage-viewport \{[^}]*border-radius: var\(--workflow-board-radius\);/s);
  assert.match(styles, /\.system-workflow__board-inspection-host \{[^}]*border-radius: var\(--workflow-board-radius\);/s);
  assert.match(styles, /\.system-workflow__metadata-projection \{[^}]*border-radius: var\(--workflow-board-radius\);/s);
  assert.match(styles, /\.system-workflow__board-window-controls,[\s\S]*?\.system-workflow__metadata-dock-controls \{[^}]*height: 100%;[^}]*align-items: center;[^}]*border-left: 1px solid var\(--workflow-border-strong\)/s);
  assert.match(board, /const sidecarOpen = metadataDocked && metadataProjection === 'side';/);
  assert.ok(board.indexOf('system-workflow__board-inspection-controls-host')
    < board.indexOf('system-workflow__metadata-dock-controls'));
  assert.doesNotMatch(board, /!inspectionActive && metadataDocked/);
  assert.match(board, /selectionOverlayHost/);
  assert.match(canvas, /createPortal\([\s\S]*system-workflow__selection-chrome[\s\S]*selectionOverlayHost/);
  assert.match(canvas, /devicePixelRatio/);
  assert.doesNotMatch(`${canvas}\n${styles}`, /system-workflow__selection-outline/);
  assert.match(styles, /\.system-workflow__resize-handle \{[^}]*border: var\(--workflow-screen-pixel, 1px\)/s);
  assert.match(styles, /\.system-workflow__progressive-media \{[^}]*overflow: visible;/s);
  assert.match(styles, /\.system-workflow__placement\[data-cropped\] \{ overflow: hidden; \}/);
  assert.doesNotMatch(styles, /\.system-workflow__placement::after/);
  assert.match(styles, /\.system-workflow__stage-viewport \{[^}]*overflow: clip;[^}]*background: var\(--workflow-board-frame-surface\);/s);
  assert.match(styles, /\.system-workflow__stage-viewport::before \{[^}]*height: 1px;[^}]*background: var\(--workflow-border-strong\);/s);
  assert.doesNotMatch(styles, /\.system-workflow__stage-viewport::after/);
  assert.match(styles, /\.lattice-focus-viewer__board-controls/);
  assert.match(styles, /\[data-inspection-atmosphere\] \.system-workflow__stage-viewport \{[\s\S]*filter: grayscale\(1\) contrast\(\.72\) brightness\(\.3\);/);
  assert.match(runtime, /inspectionAtmosphere=\{viewer\.atmosphereActive\}/);
  assert.match(styles, /\.lattice-focus-viewer__surface \{[\s\S]*background-color: rgb\(5 6 6 \/ 18%\);/);
  assert.doesNotMatch(styles, /system-workflow__board-zoom-slider|system-workflow__board-zoom-controls/);
  assert.doesNotMatch(`${board}\n${styles}`, /Zoom Board out|Zoom Board in|Fit Board|\bFIT\b|zoomWithWheel/);
  assert.equal((runtime.match(/<OwnerSystemWorkflowCanvas/g) || []).length, 1);
  assert.doesNotMatch(`${runtime}\n${board}`, /iframe|buildProfileDocumentV9|setDraft|updatePlacement/);
});
