import { PROFILE_DOCUMENT_LIMITS } from '../../src/profileDocument/domain/constants.js';
import { createProfileDocumentV9Filename, isCanonicalProfileDocumentV9Bytes } from '../../src/profileDocument/domain/profileDocumentV9Serialization.js';
import { parseProfileDocumentV9Json } from '../../src/profileDocument/domain/profileDocumentV9Validation.js';
import { isValidCid } from '../../src/profileDocument/domain/cidValidation.js';
import { FUNCTION_RESPONSE_SECURITY_HEADERS } from '../../scripts/productionSecurityPolicy.js';

const PINATA_UPLOAD_URL = 'https://uploads.pinata.cloud/v3/files';

function json(body, status = 200) {
  return Response.json(body, { status, headers: { 'cache-control': 'no-store', ...FUNCTION_RESPONSE_SECURITY_HEADERS } });
}

function requestError(code, message, status) {
  return json({ error: { code, message } }, status);
}

export function createPinProfileDocumentHandler({
  fetchImpl = fetch,
  getJwt = () => process.env.PINATA_JWT
} = {}) {
  return async function pinProfileDocument(request) {
    if (request.method !== 'POST') return requestError('METHOD_NOT_ALLOWED', 'Use POST to upload a publication', 405);

    const requestUrl = new URL(request.url);
    const origin = request.headers.get('origin');
    if (!origin || origin !== requestUrl.origin) return requestError('ORIGIN_NOT_ALLOWED', 'The upload must originate from this INSCAPE deployment', 403);

    const contentType = request.headers.get('content-type')?.split(';', 1)[0].trim().toLowerCase();
    if (contentType !== 'application/json') return requestError('UNSUPPORTED_MEDIA_TYPE', 'Expected a canonical JSON publication', 415);

    const declaredSize = Number(request.headers.get('content-length'));
    if (Number.isFinite(declaredSize) && declaredSize > PROFILE_DOCUMENT_LIMITS.maxJsonBytes) {
      return requestError('DOCUMENT_TOO_LARGE', `Publication exceeds ${PROFILE_DOCUMENT_LIMITS.maxJsonBytes} bytes`, 413);
    }

    let requestBytes;
    let document;
    try {
      requestBytes = new Uint8Array(await request.arrayBuffer());
      if (requestBytes.byteLength > PROFILE_DOCUMENT_LIMITS.maxJsonBytes) {
        return requestError('DOCUMENT_TOO_LARGE', `Publication exceeds ${PROFILE_DOCUMENT_LIMITS.maxJsonBytes} bytes`, 413);
      }
      const raw = new TextDecoder('utf-8', { fatal: true }).decode(requestBytes);
      document = parseProfileDocumentV9Json(raw);
      if (!isCanonicalProfileDocumentV9Bytes(document, requestBytes)) {
        return requestError('NON_CANONICAL_DOCUMENT', 'Upload the exact canonical publication generated by INSCAPE', 422);
      }
    } catch (error) {
      return requestError('INVALID_PROFILE_DOCUMENT', error?.message || 'The profile document is invalid', 422);
    }

    const jwt = getJwt();
    if (!jwt) return requestError('UPLOAD_NOT_CONFIGURED', 'Public IPFS upload is not configured for this deployment', 503);

    const form = new FormData();
    form.append('network', 'public');
    form.append('name', createProfileDocumentV9Filename(document));
    form.append('keyvalues', JSON.stringify({ application: 'inscape', profile: document.profile.address, documentType: document.documentType }));
    form.append('file', new Blob([requestBytes], { type: 'application/json' }), createProfileDocumentV9Filename(document));

    let upstream;
    try {
      upstream = await fetchImpl(PINATA_UPLOAD_URL, {
        method: 'POST',
        headers: { authorization: `Bearer ${jwt}` },
        body: form,
        signal: AbortSignal.timeout(45_000)
      });
    } catch (error) {
      console.error('[profile-publication-upload] Pinata request failed', { name: error?.name, message: error?.message });
      return requestError('IPFS_UPLOAD_FAILED', 'Pinata did not accept the publication; retry shortly', 502);
    }

    let payload;
    try { payload = await upstream.json(); } catch { payload = null; }
    if (!upstream.ok) {
      console.error('[profile-publication-upload] Pinata rejected upload', { status: upstream.status });
      return requestError('IPFS_UPLOAD_REJECTED', 'Pinata rejected the publication; check the server credential and retry', 502);
    }

    try {
      const cid = String(payload?.data?.cid || '');
      if (!isValidCid(cid)) throw new Error('Invalid CID');
      return json({ cid }, 201);
    } catch {
      console.error('[profile-publication-upload] Pinata returned no valid CID');
      return requestError('INVALID_IPFS_RESPONSE', 'Pinata returned an invalid upload response', 502);
    }
  };
}

export default createPinProfileDocumentHandler();

export const config = {
  path: '/api/profile-publications',
  method: 'POST',
  rateLimit: { action: 'rate_limit', aggregateBy: ['ip'], windowSize: 3600, windowLimit: 12 }
};
